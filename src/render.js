/* A collection can paint names in their own colours (`names`), wherever they
   appear on its page. Run after translation, so the dictionary only ever
   sees plain text. */
export function paintNames() {
  const main = document.querySelector('main[data-view="series"]');
  const names = main && series[main.dataset.id]?.names;
  if (!names) return;
  const find = new RegExp(`\\b(${Object.keys(names).join("|")})\\b`);
  const walker = document.createTreeWalker(main, NodeFilter.SHOW_TEXT);
  const hits = [];
  while (walker.nextNode()) if (find.test(walker.currentNode.data)) hits.push(walker.currentNode);
  // A heading that is only the name takes the colour itself, so it can still
  // be typed in letter by letter. Otherwise every odd part is a name.
  for (const node of hits) {
    const whole = names[node.data.trim()];
    if (whole && node.parentElement.childNodes.length === 1) {
      node.parentElement.classList.add("name");
      node.parentElement.style.setProperty("--c", whole);
      continue;
    }
    const parts = node.data.split(new RegExp(find, "g"));
    node.replaceWith(
      ...parts.map((part, i) =>
        i % 2 ? Object.assign(document.createElement("span"), { className: "name", textContent: part, style: `--c: ${names[part]}` }) : part,
      ),
    );
  }
}

// The home's tiles take their page's colour, and an art tile its crop, from
// the content, like the pages.
function tintTiles() {
  for (const tile of document.querySelectorAll(".work-tile")) {
    const [, section, id] = tile.getAttribute("href").match(/(art|code)\/([\w-]+)\.html/) ?? [];
    const { hue, coverPos } = (section === "art" ? series[id] : projects.find((p) => p.id === id)) ?? {};
    if (hue) tile.style.setProperty("--hue", hue);
    if (coverPos) tile.querySelector("img").style.objectPosition = coverPos;
  }
}

export function renderPage() {
  tintTiles();
  const main = document.querySelector("main[data-view]");
  if (main) VIEWS[main.dataset.view]?.(main, main.dataset.id);

  // The page was empty when the browser looked for #anchor; look again.
  if (main && location.hash)
    document.getElementById(location.hash.slice(1))?.scrollIntoView();
}
