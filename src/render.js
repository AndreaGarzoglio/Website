/* A set of pieces as a stage and a strip (behaviour in src/gallery.js). The
   stage keeps one shape for the whole set, picked from the pieces themselves,
   so flicking through them never makes the page jump; each piece sits inside
   it at its own proportions. Its caption only exists in the lightbox. */
const esc = (t = "") => t.replace(/"/g, "&quot;");

function gallery(images, { label = "", compact = false } = {}) {
  if (!images.length) return "";
  const ars = images.map(ratioOf).sort((a, b) => a - b);
  const stageAr = Math.min(1.78, Math.max(0.8, ars[Math.floor(ars.length / 2)]));
  const first = images[0];
  const thumbs = images
    .map(
      (img, i) => `
      <li><button type="button" class="gallery-thumb" style="--ar: ${ratioOf(img)}"
        data-title="${esc(img.label)}" data-caption="${esc(img.caption)}" data-ratio="${ratioOf(img)}"
        ${img.src ? `data-src="${img.src}"` : ""} ${img.full ? `data-full="${img.full}"` : ""} ${img.w ? `data-w="${img.w}"` : ""}
        aria-label="Show ${esc(img.label)}"${i === 0 ? ' aria-current="true"' : ""}>${media(img, "")}</button></li>`,
    )
    .join("");
  return `
  <div class="gallery${compact ? " gallery--compact" : ""}" data-lightbox="${esc(label)}" data-index="0">
    <figure class="gallery-stage">
      <button type="button" class="gallery-open" style="--stage-ar: ${stageAr}"
        aria-label="Open ${esc(first.label)} full screen">${
          first.src ? stageImg({ ...first, alt: first.label }) : media(first, "")
        }</button>
      <figcaption class="gallery-caption">
        <span class="gallery-count">01 / ${pad(images.length)}</span>
        <span class="gallery-title">${first.label}</span>
        <span class="gallery-hint" aria-hidden="true">click to enlarge</span>
      </figcaption>
    </figure>
    <ul class="gallery-strip"${images.length < 2 ? " hidden" : ""}>${thumbs}</ul>
  </div>`;
}

