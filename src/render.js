function renderCodeProject(main, id) {
  const p = projects.find((x) => x.id === id);
  if (!p) return;
  const link = (href, label, cls = "button") =>
    `<a class="${cls}" href="${href}" target="_blank" rel="noopener">${label}</a>`;

  main.innerHTML = `
    <article class="zone zone--page project" data-zone="code">
      <div class="shell">
        ${crumbs([["Résumé", "../index.html"], ["Code", "../code.html"], [p.title]])}
        <header class="project-head">
          ${marks[p.id] ? `<img class="project-mark" src="${marks[p.id]}" alt="" />` : ""}
          <h1 class="project-title">${p.title}</h1>
          <p class="project-tagline">${p.tagline}</p>
          <p class="project-lead">${p.lead}</p>
          <div class="project-actions">
            ${p.live ? link(p.live, "Open the live version ↗") : `<p class="entry-meta">${p.liveNote ?? ""}</p>`}
            ${link(p.repo, "Read the code ↗", "button button--ghost")}
          </div>
        </header>

        <section class="series-block">
          ${head("Screens", `${count(screensOf(p).length, "screens")}`)}
          ${gallery(screensOf(p), { label: p.title })}
        </section>

        <div class="project-grid">
          <div class="project-notes">
            ${p.notes.map(([h, t]) => `<section class="note"><h2>${h}</h2><p>${t}</p></section>`).join("")}
          </div>
          <aside class="project-side frame">
            ${
              p.shows
                ? `<h2 class="side-title">What it shows</h2>
            <ul class="shows">${p.shows.map((x) => `<li>${x}</li>`).join("")}</ul>`
                : ""
            }
            <h2 class="side-title">Built with</h2>
            <ul class="chips">${p.stack.map((s) => `<li class="chip">${s}</li>`).join("")}</ul>
            <h2 class="side-title">Links</h2>
            <ul class="link-col">
              <li>${link(p.repo, "Repository ↗", "text-link")}</li>
              ${p.live ? `<li>${link(p.live, "Live version ↗", "text-link")}</li>` : ""}
            </ul>
          </aside>
        </div>

        ${pager(`code/${p.id}.html`, "../")}
      </div>
    </article>`;
}

/* ---- Timelines ---- */

const TIMELINES = { art: artTimeline, code: codeTimeline };

function renderTimeline(el) {
  const t = TIMELINES[el.dataset.timeline];
  if (!t) return;
  el.style.setProperty("--cols", t.years.length);
  // The whole row is the link when there is somewhere to go.
  const item = (it) => `
      <li class="tl-item${it.live ? " tl-item--live" : ""}${it.href ? " tl-item--link" : ""}"
          style="--from: ${it.from}; --to: ${it.to}">
        <span class="tl-when">${it.when}</span>
        ${it.href ? `<a class="tl-what" href="${it.href}">${it.what}</a>` : `<span class="tl-what">${it.what}</span>`}
        <span class="tl-where">${it.where}</span>
      </li>`;
  el.innerHTML = `
    <div class="tl-years" aria-hidden="true">${t.years.map((y) => `<span>${y}</span>`).join("")}</div>
    ${t.lanes
      .map(
        (lane) => `
        <div class="tl-lane">
          <h3 class="tl-lane-name">${lane.name}</h3>
          <ul class="tl-track">${lane.items.map(item).join("")}</ul>
        </div>`,
      )
      .join("")}`;
}

const VIEWS = {
  art: renderArt,
  series: renderSeries,
  code: renderCode,
  "code-project": renderCodeProject,
};

export function renderPage() {
  const main = document.querySelector("main[data-view]");
  if (main) VIEWS[main.dataset.view]?.(main, main.dataset.id);
  document.querySelectorAll("[data-timeline]").forEach(renderTimeline);

  // The page was empty when the browser looked for #anchor; look again.
  if (main && location.hash) document.getElementById(location.hash.slice(1))?.scrollIntoView();
}
