function seriesBlocks(s) {
  const groups = [];

  if (s.projects) {
    groups.push({
      name: "Projects",
      blocks: s.projects.map((p) => {
        const imgs = pics(p.images);
        return {
          id: p.id,
          title: p.title,
          html: piece({
            id: p.id,
            title: p.title,
            meta: count(imgs.length, "pieces"),
            text: `<p class="piece-lead">${p.note}</p>${paras(p.concept)}${brief(p.brief)}`,
            body: gallery(imgs, { label: p.title }),
          }),
        };
      }),
    });
  }

  if (s.studies) {
    groups.push({
      name: "Studies",
      blocks: s.studies.map((st) => {
        const imgs = pics(st.images);
        return {
          id: st.id,
          title: st.title,
          html: piece({
            id: st.id,
            title: st.title,
            meta: count(imgs.length, "pieces"),
            text: `<p class="piece-lead">${st.note}</p>`,
            body: gallery(imgs, { label: st.title }),
          }),
        };
      }),
    });
  }

  if (s.pairs) {
    groups.push({
      name: "Before → now",
      blocks: s.pairs.map((pair) => ({
        id: pair.id,
        title: pair.title,
        html: piece({
          id: pair.id,
          title: pair.title,
          meta: "before → now",
          wide: true,
          text: `<p>${pair.note}</p>`,
          body: `
            <div class="pair-grid">
              <div class="pair-side">
                <span class="pair-tag">Before</span>
                ${gallery(pics(pair.before), { label: `${pair.title} · before`, compact: true })}
              </div>
              <div class="pair-arrow" aria-hidden="true">→</div>
              <div class="pair-side">
                <span class="pair-tag pair-tag--now">Now</span>
                ${gallery(pics(pair.after), { label: `${pair.title} · now`, compact: true })}
              </div>
            </div>`,
        }),
      })),
    });
  }

  if (s.extra) {
    const imgs = pics(s.extra.images);
    groups.push({
      name: "More",
      blocks: [
        {
          id: s.extra.id,
          title: s.extra.title,
          html: piece({
            id: s.extra.id,
            title: s.extra.title,
            meta: count(imgs.length, "pieces"),
            text: `<p class="piece-lead">${s.extra.note}</p>`,
            body: gallery(imgs, { label: s.extra.title }),
          }),
        },
      ],
    });
  }

  return groups;
}

