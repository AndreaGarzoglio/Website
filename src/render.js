/* A project page shows only the screens from its Drive folder. `screens`
   in code.js picks their order, names and captions: each entry is a file's
   slug (its id in images.js), the label to show and what the screen does. */
const screensOf = (p) => {
  const all = pics(p.shots);
  if (!p.screens) return all;
  return p.screens.map(([id, label, caption]) => {
    const pic = all.find((x) => x.id === id);
    if (!pic) throw new Error(`${p.id}: no screen "${id}" in ${p.shots}`);
    return { ...pic, label: t(label), caption: t(caption) };
  });
};

